function pickForeplay(part, bd, tier) {
    let pool = [];
    const inner = bd ? bd.inner : null;
    if (tier >= 3 && typeof FOREPLAY_SCENES_T3 !== 'undefined') {
        const t3 = FOREPLAY_SCENES_T3[part];
        if (t3) {
            if (t3.common) pool.push(...t3.common);
            if (inner && t3[inner]) pool.push(...t3[inner]);
        }
    }
    if (pool.length === 0 && tier >= 2 && typeof FOREPLAY_SCENES_T2 !== 'undefined') {
        const t2 = FOREPLAY_SCENES_T2[part];
        if (t2) {
            if (t2.common) pool.push(...t2.common);
            if (inner && t2[inner]) pool.push(...t2[inner]);
        }
    }
    if (pool.length === 0) {
        const scenes = FOREPLAY_SCENES[part];
        if (!scenes) return '你抚摸着她的身体，她的呼吸渐渐急促。';
        if (scenes.common) pool.push(...scenes.common);
        if (inner && scenes[inner]) pool.push(...scenes[inner]);
    }
    if (pool.length === 0) return '你抚摸着她的身体，她的呼吸渐渐急促。';
    const pair = pool[Math.floor(Math.random() * pool.length)];
    return pair[0] + ' ' + pair[1];
}

