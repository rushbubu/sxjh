function _estateProcessClothingText(text, state) {
    const c = state.clothes;
    return text
        .replace(/\{chest:([^|]*)\|([^}]*)\}/g, (_, ifOn, ifOff) => (c.outer || c.bra) ? ifOn : ifOff)
        .replace(/\{waist:([^|]*)\|([^}]*)\}/g, (_, ifOn, ifOff) => c.outer ? ifOn : ifOff)
        .replace(/\{hips:([^|]*)\|([^}]*)\}/g, (_, ifOn, ifOff) => (c.outer || c.pants) ? ifOn : ifOff)
        .replace(/\{legs:([^|]*)\|([^}]*)\}/g, (_, ifOn, ifOff) => c.pants ? ifOn : ifOff)
        .replace(/\{garden:([^|]*)\|([^}]*)\}/g, (_, ifOn, ifOff) => c.panties ? ifOn : ifOff);
}

